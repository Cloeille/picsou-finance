-- Display-only account list preferences: manual ordering and collapsing, per member.
--
-- Unlike hidden, a collapsed account stays in every total, budget and chart:
-- the list hides it behind a recap line, nothing else changes. NULL position
-- keeps creation order after the positioned rows.
--
-- One row per (member, account); absence means defaults (natural order, shown).
-- Rows reference any account the member can read (owned or shared): every viewer
-- arranges their own view without affecting anyone else's.
CREATE TABLE account_display_pref (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT      NOT NULL REFERENCES account(id) ON DELETE CASCADE,
    member_id       BIGINT      NOT NULL REFERENCES family_member(id) ON DELETE CASCADE,
    list_position   INT         NULL,
    list_collapsed  BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_account_display_pref_account_member UNIQUE (account_id, member_id)
);

-- The member lookup deliberately has no account-side index of its own: the
-- UNIQUE (account_id, member_id) constraint already indexes account_id first,
-- and per-member reads use the member index below.
CREATE INDEX idx_account_display_pref_member  ON account_display_pref (member_id);
