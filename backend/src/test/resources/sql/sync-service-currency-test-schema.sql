-- H2 fixture for real account matching and snapshot persistence without PostgreSQL-only migrations.
DROP TABLE IF EXISTS balance_snapshot;
DROP TABLE IF EXISTS account;
DROP TABLE IF EXISTS family_member;

CREATE TABLE family_member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(100) NOT NULL,
    avatar_color VARCHAR(7) NOT NULL,
    is_managed BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES family_member(id),
    name VARCHAR(100) NOT NULL,
    type VARCHAR(100) NOT NULL,
    provider VARCHAR(100),
    currency VARCHAR(10) NOT NULL,
    current_balance NUMERIC(20, 8) NOT NULL,
    cash_balance NUMERIC(20, 8),
    last_synced_at TIMESTAMP,
    payment_due_amount NUMERIC(20, 8),
    payment_due_date DATE,
    card_nature VARCHAR(20),
    reward_points BIGINT,
    external_account_id VARCHAR(255),
    is_manual BOOLEAN NOT NULL,
    color VARCHAR(7) NOT NULL,
    iban VARCHAR(34),
    ticker VARCHAR(20),
    logo_url VARCHAR(255),
    logo_key VARCHAR(32),
    requisition_id BIGINT,
    opened_at DATE,
    deleted_at TIMESTAMP,
    parent_account_id BIGINT,
    hidden BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE balance_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account(id),
    date DATE NOT NULL,
    balance NUMERIC(20, 8) NOT NULL,
    invested_amount NUMERIC(20, 8) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    UNIQUE (account_id, date)
);
