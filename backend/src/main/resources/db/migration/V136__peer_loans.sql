-- Peer loans (receivables between individuals): a counterparty, the loan terms and
-- a dated repayment ledger. Only facts are persisted; remaining capital, accrued
-- interest and the borrower history are derived on read.
--
-- See docs/decisions/2026-11-05-peer-loans-receivable.md.

CREATE TABLE peer_counterparty (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT NOT NULL REFERENCES family_member(id) ON DELETE CASCADE,
    name       VARCHAR(120) NOT NULL,
    note       VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Case-insensitive on purpose: "Marie", "marie" and "Marie " must be one borrower,
-- or the history that helps the next lending decision is split three ways.
CREATE UNIQUE INDEX uk_peer_counterparty_member_name
    ON peer_counterparty(member_id, lower(name));

CREATE TABLE peer_loan_terms (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id             BIGINT NOT NULL REFERENCES account(id) ON DELETE CASCADE,
    counterparty_id        BIGINT NOT NULL REFERENCES peer_counterparty(id),
    principal              NUMERIC(20,8) NOT NULL,
    lent_at                DATE NOT NULL,
    expected_back          DATE,
    annual_rate            NUMERIC(5,4),
    planned_monthly_amount NUMERIC(20,8),
    planned_months         INTEGER,
    linked_account_id      BIGINT REFERENCES account(id) ON DELETE SET NULL,
    note                   VARCHAR(500),
    closed_at              DATE,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_peer_loan_terms_account UNIQUE (account_id),
    CONSTRAINT ck_peer_loan_terms_principal CHECK (principal > 0),
    CONSTRAINT ck_peer_loan_terms_rate
        CHECK (annual_rate IS NULL OR (annual_rate >= 0 AND annual_rate <= 1)),
    CONSTRAINT ck_peer_loan_terms_planned
        CHECK ((planned_monthly_amount IS NULL) = (planned_months IS NULL)),
    CONSTRAINT ck_peer_loan_terms_planned_months
        CHECK (planned_months IS NULL OR planned_months > 0)
);

CREATE TABLE peer_loan_repayment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account(id) ON DELETE CASCADE,
    paid_on    DATE NOT NULL,
    amount     NUMERIC(20,8) NOT NULL,
    kind       VARCHAR(20) NOT NULL DEFAULT 'PRINCIPAL',
    note       VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_peer_loan_repayment_amount CHECK (amount > 0),
    CONSTRAINT ck_peer_loan_repayment_kind
        CHECK (kind IN ('PRINCIPAL', 'INTEREST', 'WRITE_OFF'))
);

CREATE INDEX idx_peer_loan_repayment_account_date
    ON peer_loan_repayment(account_id, paid_on);
