-- Links an external OIDC identity (issuer, subject) to an app_user.
-- email and display_name are display-only and are never used for matching.
CREATE TABLE user_identity (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL,
    issuer        VARCHAR(512) NOT NULL,
    subject       VARCHAR(255) NOT NULL,
    email         VARCHAR(320),
    display_name  VARCHAR(255),
    last_login_at TIMESTAMPTZ,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_user_identity_user
        FOREIGN KEY (user_id) REFERENCES app_user(id) ON DELETE CASCADE,
    CONSTRAINT uk_user_identity_issuer_subject UNIQUE (issuer, subject)
);

CREATE INDEX idx_user_identity_user_id ON user_identity(user_id);

ALTER TABLE persistent_session ADD COLUMN sso_authenticated_at TIMESTAMPTZ;
