-- Dividend history is global, like security_profile: an ex-date is not private data, and the
-- forecast must never call Yahoo while a page is rendering. SchedulerService warms this table
-- weekly. amount_eur is the euro figure at refresh time, so a later FX outage cannot blank a
-- forecast that was already paid for — the read path does not know Yahoo exists.
CREATE TABLE dividend_source (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker          VARCHAR(30) NOT NULL,
    currency        VARCHAR(10),
    status          VARCHAR(16) NOT NULL DEFAULT 'NEVER_FETCHED',
    refreshed_at    TIMESTAMPTZ,
    last_attempt_at TIMESTAMPTZ,
    last_error      VARCHAR(200),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_dividend_source_ticker UNIQUE (ticker),
    CONSTRAINT ck_dividend_source_status
        CHECK (status IN ('NEVER_FETCHED', 'OK', 'NO_DATA', 'FAILED'))
);

-- One row per ex-date. Relational rather than a JSON blob: the project uses no JSONB, and a
-- re-fetch replaces the set. ON DELETE CASCADE so dropping a source cannot leave orphans.
CREATE TABLE dividend_event (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id  BIGINT         NOT NULL REFERENCES dividend_source(id) ON DELETE CASCADE,
    ex_date    DATE           NOT NULL,
    amount     NUMERIC(20, 8) NOT NULL,
    amount_eur   NUMERIC(20, 8) NOT NULL,
    payment_date DATE,
    declared     BOOLEAN        NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_dividend_event_source_ex_date UNIQUE (source_id, ex_date)
);

-- What the member declared a SCPI pays, per share, and how often. Null means "not stated":
-- the forecast then stays quiet rather than inventing a cadence. The frequency check is the
-- same vocabulary the request DTO accepts; the amount check mirrors @DecimalMin("0").
ALTER TABLE scpi_position
    ADD COLUMN annual_distribution_per_share_eur NUMERIC(20, 8),
    ADD COLUMN distribution_frequency VARCHAR(20);

ALTER TABLE scpi_position
    ADD CONSTRAINT ck_scpi_position_distribution_frequency
        CHECK (distribution_frequency IS NULL
            OR distribution_frequency IN ('MONTHLY', 'QUARTERLY'));

ALTER TABLE scpi_position
    ADD CONSTRAINT ck_scpi_position_annual_distribution
        CHECK (annual_distribution_per_share_eur IS NULL
            OR annual_distribution_per_share_eur >= 0);

-- "Revenus du capital" joins the seeded default categories (CategoryService.DEFAULTS).
--
-- Dividends and SCPI distributions are recurring and none of the existing defaults describes
-- them: they landed in "Autres revenus" or stayed in the review inbox. New members get the
-- row from the seed; every member seeded before this migration needs it written here, because
-- `ensureSeeded` is a one-shot that only fires when a member has no categories at all.
--
-- Appended at the end of each member's list (MAX(sort_order) + 1) rather than slotted into
-- the seed position: renumbering would reshuffle categories the member may have reordered
-- themselves. Members with zero categories are skipped — their first read still seeds the
-- full, up-to-date default set.
INSERT INTO category (member_id, slug, name, kind, color, icon, is_default, sort_order)
SELECT c.member_id,
       'revenus-capital',
       'Revenus du capital',
       'INCOME'::category_kind,
       '#ca8a04',
       'coins',
       TRUE,
       MAX(c.sort_order) + 1
FROM category c
GROUP BY c.member_id
HAVING COUNT(*) FILTER (WHERE c.slug = 'revenus-capital') = 0;
