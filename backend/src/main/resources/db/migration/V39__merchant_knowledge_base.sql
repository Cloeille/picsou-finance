-- Merchant knowledge base (1.1.0, phase C — "zero-config" categorization).
-- A GLOBAL, offline brand dataset (not member-scoped, read-only at runtime). It lets the
-- categorizer resolve a normalized transaction label to a brand, and a brand to each
-- member's own category via the stable `slug` added in V38. Seeded here; loaded once into
-- MerchantKnowledgeBase. Privacy (ADR 2026-06-02): fully offline; logo_domain only ever
-- feeds the opt-in online logo fetch, never categorization.

-- ── Tables ──────────────────────────────────────────────────────────────────
CREATE TABLE merchant_brand (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug                  VARCHAR(60)  NOT NULL UNIQUE,
    display_name          VARCHAR(120) NOT NULL,
    default_category_slug VARCHAR(60)  NOT NULL,
    color                 VARCHAR(7),
    monogram              VARCHAR(4),
    logo_domain           VARCHAR(120)
);

-- match_type is a plain VARCHAR (WORD | PHRASE), not a native PG enum, so the set can
-- grow without an append-only enum migration. Patterns are stored already normalized
-- (lower-case, accent- and apostrophe-free) to compare directly with MerchantNormalizer.
CREATE TABLE merchant_alias (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id   BIGINT NOT NULL REFERENCES merchant_brand(id) ON DELETE CASCADE,
    pattern    VARCHAR(120) NOT NULL,
    match_type VARCHAR(10)  NOT NULL
);
CREATE INDEX idx_merchant_alias_brand ON merchant_alias(brand_id);

-- Link a transaction to the brand it was matched against (nullable; set by the categorizer).
ALTER TABLE transaction
  ADD COLUMN merchant_brand_id BIGINT REFERENCES merchant_brand(id) ON DELETE SET NULL;
CREATE INDEX idx_transaction_merchant_brand ON transaction(merchant_brand_id);

